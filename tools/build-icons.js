#!/usr/bin/env node
// Builds vendor/icons.js with ONLY the Lucide icons the app uses (instead of the whole
// ~460 KB library). Run after adding a new data-lucide="..." icon: node tools/build-icons.js
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SOURCES = ['index.html', ...fs.readdirSync(ROOT).filter(f => f.endsWith('.js'))];

global.window = global;
global.self = global;
const lucide = require('./lucide.min.js');
const version = fs.readFileSync(path.join(__dirname, 'lucide.min.js'), 'utf8').match(/lucide v([\d.]+)/)[1];

const toPascal = name => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const names = new Set();
for (const file of SOURCES) {
    for (const [, name] of fs.readFileSync(path.join(ROOT, file), 'utf8').matchAll(/data-lucide="([a-z0-9-]+)"/g)) {
        names.add(name);
    }
}

const icons = {};
for (const name of [...names].sort()) {
    const node = lucide.icons[toPascal(name)];
    if (!node) throw new Error(`Unknown Lucide icon: ${name}`);
    icons[name] = node;
}

const output = `/* Generated by tools/build-icons.js from Lucide v${version} (ISC license, see LICENSE-Lucide.txt).
   Only the ${names.size} icons used by ProCVX. Do not edit by hand. */
(function (global) {
    const ICONS = ${JSON.stringify(icons)};
    const SVG_NS = 'http://www.w3.org/2000/svg';
    const DEFAULT_ATTRS = {
        xmlns: SVG_NS, width: '24', height: '24', viewBox: '0 0 24 24', fill: 'none',
        stroke: 'currentColor', 'stroke-width': '2', 'stroke-linecap': 'round', 'stroke-linejoin': 'round'
    };

    function buildSvg(name, source) {
        const svg = global.document.createElementNS(SVG_NS, 'svg');
        Object.entries(DEFAULT_ATTRS).forEach(([key, value]) => svg.setAttribute(key, value));
        // Keep the placeholder's attributes (data-lucide, class...) like Lucide does
        Array.from(source.attributes).forEach(attr => {
            if (attr.name !== 'class') svg.setAttribute(attr.name, attr.value);
        });
        svg.setAttribute('class', ['lucide', 'lucide-' + name, source.getAttribute('class')].filter(Boolean).join(' '));
        svg.setAttribute('aria-hidden', 'true');
        ICONS[name].forEach(([tag, attrs]) => {
            const child = global.document.createElementNS(SVG_NS, tag);
            Object.entries(attrs).forEach(([key, value]) => child.setAttribute(key, value));
            svg.appendChild(child);
        });
        return svg;
    }

    // Replaces every <i data-lucide="name"> inside root (default: the whole document)
    function createIcons({ root = global.document } = {}) {
        root.querySelectorAll('[data-lucide]').forEach(el => {
            const name = el.getAttribute('data-lucide');
            if (el instanceof global.SVGElement || !ICONS[name]) return;
            el.replaceWith(buildSvg(name, el));
        });
    }

    global.ProCVXIcons = Object.freeze({ createIcons, names: Object.freeze(Object.keys(ICONS)) });
})(window);
`;
fs.writeFileSync(path.join(ROOT, 'vendor', 'icons.js'), output);
console.log(`vendor/icons.js: ${names.size} icons, ${output.length} bytes`);
